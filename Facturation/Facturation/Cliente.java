

class Cliente {
    private String nombre;
    private String id;
    private String cel;
    private String direccion;

    public Cliente(String nombre, String id, String cel, String direccion) {
        this.nombre = nombre;
        this.id = id;
        this.cel = cel;
        this.direccion = direccion;
    }
    public String getNombre() {
        return nombre;
    }
    public String getId() {
        return id;
    }
    public String getCel() {
        return cel;
    }
 
    public String getDireccion() {
        return direccion;
    }
    

    




}

 